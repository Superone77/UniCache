def _set_next_token_types(past_key_values: NaiveCache, token_type_ids: torch.Tensor) -> None:
    past_key_values.next_token_type_ids = token_type_ids.to(dtype=torch.long)


def autocast_for_device(device):
    if device.type == "cuda":
        return torch.amp.autocast(device.type, enabled=True, dtype=torch.bfloat16)
    if device.type == "mps":
        return torch.amp.autocast(device.type, enabled=True, dtype=torch.bfloat16)
    return torch.amp.autocast("cpu", enabled=False)


